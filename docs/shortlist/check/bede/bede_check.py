"""Bede BD-4C / BD-19 reference check (AER-4145).

  python3 bede/bede_check.py > bede/bede_check_output.md

Bede publishes cruise speeds at 75% and 65% power and a "maximum range" for
180 and 200 hp, but no altitude, weight or fuel flow (spec sheet
specs-bd-4c.png; the BD-19 page repeats the same table). So no published point
can calibrate the drag model. Instead this script asks four questions of the
fleet-calibrated model (run_check.py, results/bede-bd-4c.json):

  1. Speed: what our build-up gives at each published power over a range of
     altitudes, the drag factor that would match the published speed at
     8,000 ft (the highest altitude an O-360 holds 75%), and the altitude at
     which the fleet factor matches it.
  2. Range: what range 51 and 80 gal give at each published setting, at
     BSFC 0.45 (best power, our stage 1 basis) and 0.40 (lean of peak), and
     how much usable fuel the published range needs.
  3. Sensitivities of the speed to what the model had to assume: the
     slab-sided fuselage, the laminar run on the bonded wing, the gear drag.
  4. Useful load on the AM20T at the factory empty weight and at the
     kit-built fleet empty weights in the dossier.

Every number here is ours (E). Inputs: models/bede-bd-4c.json and its
results file; perf.py for the method. Nothing else is assumed.
"""
import copy
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
import perf  # noqa: E402
from run_check import AM20T, climb_allowance  # noqa: E402

KT = 1.68781
MPH_PER_KT = 1.150779
NM_PER_SM = 0.868976

m0 = json.load(open(os.path.join(HERE, "models", "bede-bd-4c.json")))
r0 = json.load(open(os.path.join(HERE, "results", "bede-bd-4c.json")))
WET = r0["wet"]
K = r0["drag_factor"]
MTOW = m0["weights"]["mtow"]
W_CRUISE = 0.92 * MTOW

# Bede spec sheet (F): (rated hp, power fraction, published mph)
PUB_SPEEDS = [(180, 0.75, 183), (180, 0.65, 174), (200, 0.75, 192), (200, 0.65, 183)]
# Bede spec sheet (F): (rated hp, max range in statute miles)
PUB_RANGE = [(180, 1026), (200, 900)]


def model(k=K, **over):
    m = copy.deepcopy(m0)
    m["drag_factor"] = k
    m.update(over)
    return m


def na_engine(hp):
    return {"hp": float(hp), "bsfc": 0.45, "crit_alt_ft": 0.0}


def speed(m, wet, hp_rated, frac, h, W=W_CRUISE):
    """KTAS at frac x rated power at altitude h, or None if a normally
    aspirated engine cannot make that power there."""
    eng = na_engine(hp_rated)
    P = frac * hp_rated
    if perf.power_avail(eng, h, 1.0) < P - 0.5:
        return None
    return perf.solve_speed(m, wet, eng, W, h, P)["ktas"]


def k_to_match(hp_rated, frac, h, ktas_pub):
    lo, hi = 0.5, 3.0
    for _ in range(40):
        k = 0.5 * (lo + hi)
        v = speed(model(k), WET, hp_rated, frac, h)
        lo, hi = (k, hi) if v > ktas_pub else (lo, k)
    return 0.5 * (lo + hi)


def alt_to_match(hp_rated, frac, ktas_pub):
    """Altitude at which the fleet-factor model reaches the published speed,
    within the altitudes where the engine still makes the power."""
    best = None
    for h in range(0, 14001, 250):
        v = speed(model(), WET, hp_rated, frac, float(h))
        if v is None:
            break
        if v >= ktas_pub:
            return h
        best = h
    return None


def range_nm(m, wet, hp_rated, frac, h, gal, bsfc, reserve_min=0.0):
    eng = na_engine(hp_rated)
    P = frac * hp_rated
    V = perf.solve_speed(m, wet, eng, W_CRUISE, h, P)["V_fts"]
    fuel = gal * 6.0
    clb = climb_allowance(MTOW, h, bsfc=bsfc)
    rng, _ = perf.cruise_range(m, wet, MTOW - clb, fuel - clb, h, V, bsfc, 1, reserve_min)
    return rng


def gal_for(m, wet, hp_rated, frac, h, dist_nm, bsfc):
    eng = na_engine(hp_rated)
    V = perf.solve_speed(m, wet, eng, W_CRUISE, h, frac * hp_rated)["V_fts"]
    clb = climb_allowance(MTOW, h, bsfc=bsfc)
    return (perf.fuel_for(m, wet, MTOW - clb, dist_nm, h, V, bsfc) + clb) / 6.0


def main():
    P = print
    m = model()
    P("# Bede BD-4C / BD-19 reference check (AER-4145)\n")
    P(f"Generated by `bede/bede_check.py`. Model `models/bede-bd-4c.json`, fleet drag factor "
      f"{K:.2f} (no published point states altitude or power, so the fleet factor is used). "
      f"Cruise weight 0.92 x {MTOW:,} lb. Every number is ours (E).\n")

    P("## 1. Published speeds against our build-up\n")
    P("Bede's figures are mph at 75% and 65% power, no altitude stated (F). Ours: KTAS at "
      "the same power at each altitude, fleet factor; '-' where an O-360/IO-360 cannot make "
      "that power (Gagg-Ferrar lapse).\n")
    alts = [0, 4000, 8000, 10000]
    P("| Rated hp, power | Published, mph / KTAS | " + " | ".join(f"Ours at {a:,} ft" for a in alts)
      + " | Factor to match at 8,000 ft | Altitude where the fleet factor matches |")
    P("|---|---|" + "---|" * len(alts) + "---|---|")
    for hp, frac, mph in PUB_SPEEDS:
        kt = mph / MPH_PER_KT
        cells = []
        for a in alts:
            v = speed(m, WET, hp, frac, float(a))
            cells.append("-" if v is None else f"{v:.0f}")
        k8 = k_to_match(hp, frac, 8000.0, kt) if speed(m, WET, hp, frac, 8000.0) else None
        am = alt_to_match(hp, frac, kt)
        P(f"| {hp} hp, {frac:.0%} | {mph} / {kt:.0f} | " + " | ".join(cells)
          + f" | {'-' if k8 is None else f'{k8:.2f}'} | "
          + ("not reached while the engine makes the power" if am is None else f"{am:,} ft") + " |")
    P("")
    P("Fleet calibration band for comparison: 1.16-1.36 (Express, P210N, Cozy). A factor "
      "inside it means the published speed is consistent with the geometry; below it, the "
      "published speed reads cleaner than any measured airplane in the survey.\n")

    P("## 2. Published range against the fuel\n")
    P("Still air, from gross with the stage 3 taxi and climb allowance, no descent credit, "
      "8,000 ft. 'Gal needed' is the usable fuel the published range needs with no reserve "
      "at that setting.\n")
    P("| Rated hp, power | KTAS (ours) | BSFC | 51 gal, nm, no reserve / 45 min | 80 gal, nm, no reserve / 45 min | Published max range, nm | Gal needed for it, no reserve |")
    P("|---|---|---|---|---|---|---|")
    for hp, rsm in PUB_RANGE:
        rnm = rsm * NM_PER_SM
        for frac in (0.75, 0.65, 0.55):
            v = speed(m, WET, hp, frac, 8000.0)
            for bsfc in (0.45, 0.40):
                a = [range_nm(m, WET, hp, frac, 8000.0, g, bsfc, rv) for g in (51, 80) for rv in (0.0, 45.0)]
                need = gal_for(m, WET, hp, frac, 8000.0, rnm, bsfc)
                P(f"| {hp} hp, {frac:.0%} | {v:.0f} | {bsfc:.2f} | {a[0]:,.0f} / {a[1]:,.0f} | "
                  f"{a[2]:,.0f} / {a[3]:,.0f} | {rnm:,.0f} ({rsm:,} sm) | {need:.0f} |")
    P("")

    P("## 3. Sensitivity of the speed to what the model assumed\n")
    P("180 hp at 75% (135 hp), 8,000 ft, fleet factor. Each row changes one input.\n")
    P("| Case | KTAS | Change |")
    P("|---|---|---|")
    base = speed(m, WET, 180, 0.75, 8000.0)
    P(f"| Baseline model | {base:.1f} | - |")
    cases = []
    w2 = copy.deepcopy(WET)
    # slab-sided box: perimeter of a w x h rectangle against the ellipse the model lofts
    w, h = m0["fuselage"]["width"], m0["fuselage"]["height"]
    import math
    a_, b_ = w / 2, h / 2
    ell = math.pi * (3 * (a_ + b_) - math.sqrt((3 * a_ + b_) * (a_ + 3 * b_)))
    box = 2 * (w + h)
    w2["Fuselage"] = dict(w2["Fuselage"], wet_ft2=w2["Fuselage"]["wet_ft2"] * box / ell)
    cases.append((f"Slab-sided fuselage: wetted area x {box/ell:.2f} (box perimeter over the "
                  f"model's ellipse at the cabin)", m, w2))
    for xtr in (0.10, 0.35):
        mm = model()
        for c in mm["components"]:
            if c["name"] == "Wing":
                c["xtr"] = xtr
        cases.append((f"Wing laminar run x_tr {xtr:.2f} (baseline 0.25)", mm, WET))
    for dq in (0.45, 0.80):
        cases.append((f"Gear D/q {dq:.2f} ft2 (baseline 0.60)", model(fixed_Dq=[["gear", dq]]), WET))
    cases.append(("Drag factor 1.16 (fleet low end)", model(1.16), WET))
    cases.append(("Drag factor 1.36 (fleet high end)", model(1.36), WET))
    for name, mm, ww in cases:
        v = speed(mm, ww, 180, 0.75, 8000.0)
        P(f"| {name} | {v:.1f} | {v - base:+.1f} kt ({(v / base - 1) * 100:+.1f}%) |")
    P("")

    P("## 4. Useful load on the AM20T at the empty weights on record\n")
    dm = r0["am_dmass_lb"]
    P(f"AM20T installed-mass change against the 180 hp O-360: {dm:+.0f} lb (stage 3 basis, "
      f"no credit taken for a lighter engine). Gross {MTOW:,} lb.\n")
    P("| Empty weight basis | Empty, lb, as recorded | With the AM20T, lb | Useful load, lb | Against 1,000 lb |")
    P("|---|---|---|---|---|")
    for label, ew in EMPTIES:
        e = ew + max(dm, 0.0)
        ul = MTOW - e
        P(f"| {label} | {ew:,} | {e:,.0f} | {ul:,.0f} | {ul - 1000:+,.0f} lb ({(ul / 1000 - 1) * 100:+.0f}%) |")
    P("")


# Empty weights to report useful load on (sources and grades in the dossier).
# The AM20T delta is taken against the O-360 for every row; for the IO-360
# airplanes it overstates the delta by a few tens of lb.
EMPTIES = [
    ("BD-4C factory, spec sheet (F)", 1250),
    ("BD-4C factory, page text (F; disagrees with the sheet)", 1200),
    ("BD-4C N2468Z, builder's published weight, IO-360-A1A 200 hp (B)", 1281),
    ("BD-4 N186JB, 1986, O-360 180 hp, for-sale ad c. 2001 (B)", 1340),
    ("BD-4 'approx', 1997, O-320 160 hp, long wings, for-sale ad (B)", 1300),
    ("BD-4 builders' FAQ range, low end (B)", 1200),
    ("BD-4 builders' FAQ range, high end (B)", 1500),
]


def owner_point():
    """N2468Z (BD-4C, IO-360-A1A 200 hp): '142 knots TAS' at 'Cruise @ 65%
    (without gear fairings)', 48 gal, '717 nm' at 65% (builder's blog, B).
    No altitude or weight is given, so it cannot calibrate; this asks whether
    the model, with unfaired gear, brackets it."""
    P = print
    P("## 5. Owner-reported BD-4C points (N2468Z, B)\n")
    P("130 hp (65% of 200), 0.92 x gross, fleet factor. Gear D/q 0.60 ft2 is the model's spatted "
      "gear; 0.90 ft2 is our allowance for the same gear without fairings (E). Range: 48 gal, "
      "no reserve, from gross, BSFC 0.45 / 0.40.\n")
    P("| Gear | " + " | ".join(f"KTAS at {a:,} ft" for a in (0, 4000, 8000)) + " | 48 gal range at 8,000 ft, nm, BSFC 0.45 / 0.40 |")
    P("|---|---|---|---|---|")
    for dq in (0.60, 0.90):
        mm = model(fixed_Dq=[["gear", dq]])
        v = [speed(mm, WET, 200, 0.65, float(a)) for a in (0, 4000, 8000)]
        rr = [range_nm(mm, WET, 200, 0.65, 8000.0, 48, b) for b in (0.45, 0.40)]
        P(f"| D/q {dq:.2f} | " + " | ".join(f"{x:.0f}" for x in v) + f" | {rr[0]:,.0f} / {rr[1]:,.0f} |")
    P("\nPublished by the builder: 142 KTAS and 717 nm at 65% (B; altitude, weight and "
      "reserve not stated).\n")
    P("The same builder's April 2019 fuel-flow flight (B), before gear fairings and gap seals: "
      "'Airspeed: 133 knots', 11.6 gph at 75% (2,400 rpm, 24.4 in), outbound at 4,500 ft; "
      "'Airspeed: 125 knots', 8.4 gph at 65% (2,400 rpm, 21.6 in), at 5,500 ft. The post does "
      "derives 133.5 kt from a three-heading GPS run, which gives true airspeed, and finds the "
      "indicator within 1.1 kt of it, so the TAS reading is the one to use; the IAS reading "
      "(TAS = IAS / sqrt(sigma), standard day) is shown only as the most generous bound. Drag "
      "factor to match, with the unfaired-gear allowance (D/q 0.90):\n")
    P("| Point | hp (owner's % of 200) | Read as TAS: KTAS / factor | Read as IAS: KTAS / factor | Implied BSFC, lb/hp/h |")
    P("|---|---|---|---|---|")
    for kt, h, frac, gph in ((133.0, 4500.0, 0.75, 11.6), (125.0, 5500.0, 0.65, 8.4)):
        cells = []
        for ktas in (kt, kt / perf.atmos(h)[3] ** 0.5):
            lo, hi = 0.5, 3.0
            for _ in range(40):
                k = 0.5 * (lo + hi)
                v = speed(model(k, fixed_Dq=[["gear", 0.90]]), WET, 200, frac, h)
                lo, hi = (k, hi) if v > ktas else (lo, k)
            cells.append(f"{ktas:.0f} / {0.5 * (lo + hi):.2f}")
        P(f"| {kt:.0f} kt at {h:,.0f} ft, {frac:.0%} | {frac * 200:.0f} | {cells[0]} | {cells[1]} | "
          f"{gph * 6 / (frac * 200):.2f} |")
    P("\nAn incomplete airframe (no fairings, unsealed wing-root and tip gaps, long exhaust "
      "stacks, per the builder) and power taken from the owner's MP/rpm table, so these bound "
      "the as-first-flown airplane; they do not calibrate the finished one.\n")
    P("## 6. The AM20T on the as-first-flown drag basis\n")
    P("What the stage 3 AM20T cases give if the airplane is as draggy as N2468Z first flew "
      "(factor 1.77 with unfaired gear, from section 5), against the headline (fleet 1.29, "
      "spatted gear). 195 hp continuous, assumed, as everywhere in the survey.\n")
    P("| Basis | KTAS, AM-low (8,000 ft) | KTAS, AM-high (16,000 ft) |")
    P("|---|---|---|")
    for label, mm in (("Headline: fleet factor 1.29, spatted gear", model()),
                      ("As first flown: factor 1.77, unfaired gear", model(1.77, fixed_Dq=[["gear", 0.90]]))):
        v = []
        for crit in (8000.0, 16000.0):
            eng = dict(AM20T, crit_alt_ft=crit)
            Pw = perf.power_avail(eng, crit, eng["cont_hp"] / eng["hp"])
            v.append(perf.solve_speed(mm, WET, eng, W_CRUISE, crit, Pw)["ktas"])
        P(f"| {label} | {v[0]:.0f} | {v[1]:.0f} |")
    P("")

if __name__ == "__main__":
    main()
    owner_point()
