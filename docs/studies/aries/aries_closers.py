"""AER-3867 follow-up to aries_check.py: combined gap closers.

For each assumed engine base (AM-low, AM-high), with the calibrated drag
factor from results.json:
  - usable fuel needed for 1,000 nm + 45 min at 160 KTAS (the speed floor),
    and at 65% of take-off power;
  - the take-off weight that carries 1,000 lb of payload over 1,000 nm + 45
    min at 160 KTAS and at 65% of take-off power (MTOW-limited case);
  - the fastest speed that makes 1,000 nm + 45 min with 90 gal usable, with
    all five drag items of aries_check.py on 76 gal, and with both. Every
    "fastest" speed is capped at what continuous power reaches.

Run from the repo root after aries_check.py:
  python3 docs/studies/aries/aries_closers.py   -> closers.json, closers.md
"""
import json
import os

import aries_check as A

perf = A.perf
HERE = A.HERE


def tow_for_payload(m, wet, eng, h, V, empty, payload, reserve):
    for dW in range(0, 801, 10):
        W0 = 3150 + dW
        clb = A.run_check.climb_allowance(W0, h, bsfc=eng["bsfc"])
        f = perf.fuel_for(m, wet, W0 - clb, 1000.0, h, V, eng["bsfc"], 1, reserve) + clb
        if W0 - empty - f >= payload:
            return dW, f / A.DENS
    return None, None


def main():
    res = json.load(open(os.path.join(HERE, "results.json")))
    k = res["calibration"]["k"]
    m, wet = A.load()
    m["drag_factor"] = k
    md, wd = A.perturb(m, wet, "xtr_wing", 0.40)
    md["drag_factor"] = k
    md["cooling_factor"] = 0.60
    md["delta_Dq_post"] = -0.06
    md["prop"]["install"] = 1.03
    out = {"k": k}
    for case in ("AM-low", "AM-high"):
        eng = A.engine(case)
        h = A.CRUISE_ALT[case]
        o = {}
        V160 = 160 * A.FT_PER_KT
        o["hp_at_160kt"] = A.power_at(m, wet, 0.92 * 3150, h, V160)
        o["gal_1000_45_at_160kt"] = A.gal_for(m, wet, eng, h, V160, 3150, 45.0)
        V65 = A.setting_speed(m, wet, eng, h, 0.65 * 260, 3150)
        o["ktas_65pct"] = V65 / A.FT_PER_KT
        o["gal_1000_45_at_65pct"] = A.gal_for(m, wet, eng, h, V65, 3150, 45.0)
        dW, gal = tow_for_payload(m, wet, eng, h, V160, 1850.0, 1000.0, 45.0)
        o["tow_1000lb_payload_160kt_45"] = {"dW": dW, "gal": gal}
        dW, gal = tow_for_payload(m, wet, eng, h, V65, 1850.0, 1000.0, 45.0)
        o["tow_1000lb_payload_65pct_45"] = {"dW": dW, "gal": gal}
        Pc = perf.power_avail(eng, h, eng["cont_hp"] / eng["hp"])
        vmax = round(A.setting_speed(m, wet, eng, h, Pc, 3150) / A.FT_PER_KT)
        vmax_d = round(A.setting_speed(md, wd, eng, h, Pc, 3150) / A.FT_PER_KT)
        o["vmax_cont"], o["vmax_cont_drag_items"] = vmax, vmax_d
        o["fastest_1000_45_90gal"] = min(A.speed_for_range(m, wet, eng, h, 3150, 90 * A.DENS, 45.0), vmax)
        o["drag_items_fastest_1000_45_76gal"] = min(A.speed_for_range(md, wd, eng, h, 3150, 76 * A.DENS, 45.0), vmax_d)
        o["drag_items_fastest_1000_45_90gal"] = min(A.speed_for_range(md, wd, eng, h, 3150, 90 * A.DENS, 45.0), vmax_d)
        out[case] = o
    json.dump(out, open(os.path.join(HERE, "closers.json"), "w"), indent=1, default=float)
    L = ["# AER-3867 combined closers (generated by aries_closers.py)", "",
         f"Drag factor {k:.3f}. AM20T 195 hp continuous, BSFC 0.45 and critical altitudes ASSUMED.", "",
         "| | AM-low (8,000 ft) | AM-high (16,000 ft) |", "|---|---|---|"]
    lo, hi = out["AM-low"], out["AM-high"]
    rows = [
        ("Power for 160 KTAS at 0.92 MTOW, hp", "hp_at_160kt", "{:.0f}"),
        ("Usable fuel for 1,000 nm + 45 min at 160 KTAS, gal", "gal_1000_45_at_160kt", "{:.1f}"),
        ("KTAS at 65% of take-off (169 hp)", "ktas_65pct", "{:.0f}"),
        ("Usable fuel for 1,000 nm + 45 min at 65% of take-off, gal", "gal_1000_45_at_65pct", "{:.1f}"),
        ("KTAS at continuous power (ceiling for the rows below)", "vmax_cont", "{}"),
        ("Same, with all five drag items", "vmax_cont_drag_items", "{}"),
        ("Fastest KTAS for 1,000 nm + 45 min, 90 gal usable", "fastest_1000_45_90gal", "{}"),
        ("Fastest KTAS for 1,000 nm + 45 min, all five drag items, 76 gal", "drag_items_fastest_1000_45_76gal", "{}"),
        ("Fastest KTAS for 1,000 nm + 45 min, all five drag items, 90 gal", "drag_items_fastest_1000_45_90gal", "{}"),
    ]
    for lab, key, fmt in rows:
        L.append(f"| {lab} | {fmt.format(lo[key])} | {fmt.format(hi[key])} |")
    for lab, key in [("Take-off weight increase for 1,000 lb payload, 1,000 nm + 45 min, at 160 KTAS", "tow_1000lb_payload_160kt_45"),
                     ("Same, at 65% of take-off power", "tow_1000lb_payload_65pct_45")]:
        a, b = lo[key], hi[key]
        L.append(f"| {lab} | +{a['dW']} lb ({a['gal']:.0f} gal) | +{b['dW']} lb ({b['gal']:.0f} gal) |")
    open(os.path.join(HERE, "closers.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
