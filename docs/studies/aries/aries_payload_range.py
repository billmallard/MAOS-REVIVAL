"""AER-3867 follow-up to aries_check.py: the payload-range tradeoff.

Bill's ruling of 2026-10-25 (BRIEF.md): useful load and range are targets,
not floors, and the check reports the payload-range tradeoff instead of a
joint verdict. This script gives that tradeoff on the standard airframe
(MTOW 3,150 lb, empty 1,850 lb, 76 gal usable) at three cruise speeds:

  - 160 KTAS, the speed floor;
  - 65% of take-off power (169 hp);
  - continuous power (195 hp, assumed).

For each payload, fuel is the smaller of full tanks and what MTOW allows;
take-off weight is empty + payload + fuel. Range with no reserve and with
45 min at cruise power, on both assumed engine bases. Same drag factor,
climb allowance and BSFC (0.45, assumed) as aries_check.py.

Run from the repo root after aries_check.py:
  python3 docs/studies/aries/aries_payload_range.py   -> payload_range.json, payload_range.md
"""
import json
import os

import aries_check as A

perf = A.perf
HERE = A.HERE
MTOW, EMPTY, FUEL_MAX = 3150.0, 1850.0, 76 * A.DENS
PAYLOADS = [400, 544, 600, 700, 800, 844, 900, 1000, 1100]


def main():
    k = json.load(open(os.path.join(HERE, "results.json")))["calibration"]["k"]
    m, wet = A.load()
    m["drag_factor"] = k
    out = {"k": k}
    for case in ("AM-low", "AM-high"):
        eng = A.engine(case)
        h = A.CRUISE_ALT[case]
        Pc = perf.power_avail(eng, h, eng["cont_hp"] / eng["hp"])
        speeds = {"160 KTAS (floor)": 160 * A.FT_PER_KT,
                  "65% of take-off (169 hp)": A.setting_speed(m, wet, eng, h, 0.65 * 260, MTOW),
                  "continuous (195 hp)": A.setting_speed(m, wet, eng, h, Pc, MTOW)}
        rows = []
        for sname, V in speeds.items():
            for pay in PAYLOADS:
                fuel = min(FUEL_MAX, MTOW - EMPTY - pay)
                W0 = EMPTY + pay + fuel
                rows.append({"speed": sname, "ktas": V / A.FT_PER_KT, "payload": pay,
                             "fuel_gal": fuel / A.DENS, "W0": W0,
                             "nm0": A.fly(m, wet, eng, h, V, W0, fuel, 0.0),
                             "nm45": A.fly(m, wet, eng, h, V, W0, fuel, 45.0)})
        out[case] = rows
    json.dump(out, open(os.path.join(HERE, "payload_range.json"), "w"), indent=1, default=float)
    L = ["# AER-3867 payload-range tradeoff (generated by aries_payload_range.py)", "",
         f"Drag factor {k:.3f}. MTOW 3,150 lb, empty 1,850 lb (factory; no weighed figure), 76 gal usable (TCDS).",
         "AM20T 195 hp continuous, BSFC 0.45 and critical altitudes ASSUMED. Every number is grade E (ours).",
         "Payload = people and baggage. Fuel is full tanks or what MTOW allows, whichever is less.", ""]
    for case in ("AM-low", "AM-high"):
        L += [f"## {case} (cruise at {A.CRUISE_ALT[case]:,.0f} ft)", "",
              "| Payload, lb | Fuel, gal | Take-off, lb | " +
              " | ".join(f"{s}{out[case][i * len(PAYLOADS)]['ktas']:.0f} KTAS: nm, none / 45 min"
                         for i, s in enumerate(["", "65% take-off, ", "continuous, "])) + " |",
              "|---|---|---|---|---|---|"]
        n = len(PAYLOADS)
        for j, pay in enumerate(PAYLOADS):
            r = [out[case][i * n + j] for i in range(3)]
            L.append(f"| {pay:,} | {r[0]['fuel_gal']:.0f} | {r[0]['W0']:,.0f} | " +
                     " | ".join(f"{x['nm0']:,.0f} / {x['nm45']:,.0f}" for x in r) + " |")
        L.append("")
    open(os.path.join(HERE, "payload_range.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
